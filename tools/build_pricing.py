"""Builds js/pricing.js from Adam's engine.js, byte-for-byte unchanged.
The wrapper only gives it its own scope: engine.js declares globals named quote, DEF and r, which
would collide with the app's names in a classic <script>. Rerun after any engine update:
  python3 tools/build_pricing.py /workspace/finance/pricing_v4/engine.js"""
import sys, hashlib
src = open(sys.argv[1] if len(sys.argv) > 1 else '/workspace/finance/pricing_v4/engine.js').read()
h = hashlib.sha256(src.encode()).hexdigest()
out = ("/* GENERATED by tools/build_pricing.py. Do not edit. Pricing engine v4 (Adam), engine.js embedded verbatim.\n"
       f"   engine.js sha256: {h}\n   PROTOTYPE: prices are calculated in the browser for display only. The real build must price on the server. */\n"
       "const PricingEngine = (function () {\n/* ---- engine.js (verbatim) ---- */\n" + src +
       "\n/* ---- end engine.js ---- */\nreturn { quote, DEF };\n})();\n"
       "if (typeof module !== 'undefined') module.exports = PricingEngine;\n")
open('js/pricing.js', 'w').write(out); print('js/pricing.js', h)
